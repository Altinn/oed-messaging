using Altinn.Dd.Tests.Shared;
using System.Globalization;
using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;

namespace Altinn.Dd.Tests.SonarGate.Internal;

/// <summary>
/// Writes per-run JSON snapshots and regenerates the consumer's <c>history/summary.md</c>.
/// All paths are local to the consumer's QaTests folder; the dd-qa publish step (see
/// <c>DdQaPublisher</c>) is responsible for mirroring these to the central repo.
/// </summary>
internal sealed class HistoryWriter
{
    private static readonly JsonSerializerOptions HistoryJsonOptions = new()
    {
        WriteIndented = true,
        PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
    };

    private readonly string _historyDir;
    private readonly string _projectKey;

    public HistoryWriter(string historyDir, string projectKey)
    {
        _historyDir = historyDir;
        _projectKey = projectKey;
    }

    public string WriteSnapshot(QualityGate gate, Dictionary<string, string> metrics, TopFindings top, string? commitSha)
    {
        Directory.CreateDirectory(_historyDir);
        var ts = DateTime.UtcNow;
        var snapshot = new
        {
            Timestamp = ts.ToString("O", CultureInfo.InvariantCulture),
            ProjectKey = _projectKey,
            // Consumed by the unchanged-HEAD skip on the next run (BlobArchiver.GetLastArchivedCommitShaAsync).
            CommitSha = commitSha,
            QualityGate = new { gate.Status, gate.Conditions },
            Metrics = metrics,
            Top = new
            {
                top.Bugs,
                top.CodeSmells,
                top.Hotspots,
            },
        };
        var file = Path.Combine(_historyDir, $"{ts:yyyyMMdd-HHmmss}.json");
        File.WriteAllText(file, JsonSerializer.Serialize(snapshot, HistoryJsonOptions));
        return file;
    }

    /// <summary>
    /// This gate's own snapshots: <c>yyyyMMdd-HHmmss.json</c>. The history folder is shared with
    /// other gates whose snapshots have a different shape, so every read here is scoped through
    /// <see cref="HistoryFolder"/> — see its docs for what goes wrong otherwise.
    /// </summary>
    internal static readonly Regex SnapshotNamePattern =
        new(@"^\d{8}-\d{6}\.json$", RegexOptions.Compiled | RegexOptions.CultureInvariant);

    public void RegenerateSummary()
    {
        var rows = new List<(DateTime Ts, string Status, Dictionary<string, string> Metrics)>();
        foreach (var file in HistoryFolder.Snapshots(_historyDir, SnapshotNamePattern))
        {
            using var doc = JsonDocument.Parse(File.ReadAllText(file));
            var root = doc.RootElement;
            var ts = DateTime.Parse(
                root.GetProperty("timestamp").GetString()!,
                CultureInfo.InvariantCulture,
                DateTimeStyles.RoundtripKind);
            var status = root.GetProperty("qualityGate").GetProperty("status").GetString() ?? "?";
            var ms = new Dictionary<string, string>(StringComparer.Ordinal);
            foreach (var p in root.GetProperty("metrics").EnumerateObject())
                ms[p.Name] = p.Value.GetString() ?? "";
            rows.Add((ts, status, ms));
        }
        rows.Sort((a, b) => b.Ts.CompareTo(a.Ts));

        var sb = new StringBuilder();
        sb.AppendLine($"# {_projectKey} history");
        sb.AppendLine();
        sb.AppendLine("Auto-generated by `Altinn.Dd.Tests.SonarGate`. Latest run first, up to 30 shown. ");
        sb.AppendLine("Per-run JSON snapshots in this folder hold the full history.");
        sb.AppendLine();
        sb.AppendLine("| Timestamp (UTC) | Gate | Bugs | Vulns | Smells | Hotspots | Coverage % | Dup % | NCLOC | Debt (h) |");
        sb.AppendLine("|---|---|---:|---:|---:|---:|---:|---:|---:|---:|");
        foreach (var (ts, status, m) in rows.Take(30))
        {
            sb.Append("| ").Append(ts.ToString("yyyy-MM-dd HH:mm:ss", CultureInfo.InvariantCulture))
              .Append(" | ").Append(status)
              .Append(" | ").Append(V(m, "bugs"))
              .Append(" | ").Append(V(m, "vulnerabilities"))
              .Append(" | ").Append(V(m, "code_smells"))
              .Append(" | ").Append(V(m, "security_hotspots"))
              .Append(" | ").Append(V(m, "coverage"))
              .Append(" | ").Append(V(m, "duplicated_lines_density"))
              .Append(" | ").Append(V(m, "ncloc"))
              .Append(" | ").Append(DebtHours(V(m, "sqale_index")))
              .AppendLine(" |");
        }

        AppendLatestRunDetails(sb);

        File.WriteAllText(Path.Combine(_historyDir, "summary.md"), sb.ToString());

        static string V(Dictionary<string, string> m, string key)
            => m.TryGetValue(key, out var v) && !string.IsNullOrEmpty(v) ? v : "-";

        static string DebtHours(string sqaleIndex)
            => int.TryParse(sqaleIndex, NumberStyles.Integer, CultureInfo.InvariantCulture, out var min)
                ? (min / 60.0).ToString("0.0", CultureInfo.InvariantCulture)
                : "-";
    }

    // Renders the top-N findings from the most recent snapshot only. Older snapshots still carry
    // their own `top` block in JSON, but listing them all in markdown would defeat the size cap.
    private void AppendLatestRunDetails(StringBuilder sb)
    {
        var latestFile = HistoryFolder.Newest(_historyDir, SnapshotNamePattern);
        if (latestFile is null) return;

        using var doc = JsonDocument.Parse(File.ReadAllText(latestFile));
        if (!doc.RootElement.TryGetProperty("top", out var top)) return;

        var ts = DateTime.Parse(
            doc.RootElement.GetProperty("timestamp").GetString()!,
            CultureInfo.InvariantCulture,
            DateTimeStyles.RoundtripKind);

        // Heading is intentionally timestamp-free so external links (e.g. dd-qa root README) can use
        // a stable `#latest-run-details` anchor that survives every regeneration.
        sb.AppendLine();
        sb.AppendLine("## Latest run details");
        sb.AppendLine();
        sb.AppendLine($"_Run at {ts.ToString("yyyy-MM-dd HH:mm:ss", CultureInfo.InvariantCulture)} UTC._");
        AppendTopIssues(sb, top, "bugs", $"Top {SonarQubeApi.TopN} bugs");
        AppendTopIssues(sb, top, "codeSmells", $"Top {SonarQubeApi.TopN} code smells");
        AppendTopHotspots(sb, top);
    }

    private static void AppendTopIssues(StringBuilder sb, JsonElement top, string property, string heading)
    {
        if (!top.TryGetProperty(property, out var arr) || arr.GetArrayLength() == 0) return;
        sb.AppendLine();
        sb.AppendLine($"### {heading}");
        sb.AppendLine();
        sb.AppendLine("| Severity | Rule | Location | Message |");
        sb.AppendLine("|---|---|---|---|");
        foreach (var i in arr.EnumerateArray())
        {
            sb.Append("| ").Append(Markdown.Cell(Json.GetStringOrEmpty(i, "severity")))
              .Append(" | ").Append(Markdown.Cell(Json.GetStringOrEmpty(i, "rule")))
              .Append(" | ").Append(Markdown.Cell(LocationCell(i)))
              .Append(" | ").Append(Markdown.Cell(Json.GetStringOrEmpty(i, "message")))
              .AppendLine(" |");
        }
    }

    private static void AppendTopHotspots(StringBuilder sb, JsonElement top)
    {
        if (!top.TryGetProperty("hotspots", out var arr) || arr.GetArrayLength() == 0) return;
        sb.AppendLine();
        sb.AppendLine($"### Top {SonarQubeApi.TopN} hotspots");
        sb.AppendLine();
        sb.AppendLine("| Probability | Category | Rule | Location | Message |");
        sb.AppendLine("|---|---|---|---|---|");
        foreach (var h in arr.EnumerateArray())
        {
            sb.Append("| ").Append(Markdown.Cell(Json.GetStringOrEmpty(h, "vulnerabilityProbability")))
              .Append(" | ").Append(Markdown.Cell(Json.GetStringOrEmpty(h, "securityCategory")))
              .Append(" | ").Append(Markdown.Cell(Json.GetStringOrEmpty(h, "rule")))
              .Append(" | ").Append(Markdown.Cell(LocationCell(h)))
              .Append(" | ").Append(Markdown.Cell(Json.GetStringOrEmpty(h, "message")))
              .AppendLine(" |");
        }
    }

    private static string LocationCell(JsonElement el)
    {
        var component = Json.GetStringOrEmpty(el, "component");
        var line = Json.GetIntOrNull(el, "line");
        return line.HasValue ? $"{component}:{line.Value}" : component;
    }
}
